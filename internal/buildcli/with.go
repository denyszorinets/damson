// Package buildcli implements "damson build": it builds a custom damson binary
// with extra plugin modules linked in (ADR-0050).
package buildcli

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"runtime/debug"
	"strconv"
	"strings"
)

// DamsonModule is the module path of Damson itself.
const DamsonModule = "github.com/denyszorinets/damson"

var (
	modulePathRe    = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._~/-]*$`)
	damsonVersionRe = regexp.MustCompile(`^v\d+\.\d+\.\d+([-+][0-9A-Za-z.+-]+)?$`)
	versionRe       = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._+-]*$`)
)

// With is one --with argument: module[@version][=dir].
type With struct {
	Path    string
	Version string // "latest" when not given and no Dir
	Dir     string // absolute; empty for a remote module
}

// parseWith parses and checks one --with value. Go validates the rest.
func parseWith(s string) (With, error) {
	var w With
	spec, dir, hasDir := strings.Cut(s, "=")
	path, ver, hasVer := strings.Cut(spec, "@")
	if hasDir && hasVer {
		return w, fmt.Errorf("--with %q: a version and a directory cannot be combined", s)
	}
	if err := checkModulePath(path); err != nil {
		return w, fmt.Errorf("--with %q: %w", s, err)
	}
	w.Path = path
	switch {
	case hasDir:
		abs, err := filepath.Abs(dir)
		if err != nil {
			return w, fmt.Errorf("--with %q: %w", s, err)
		}
		if _, err := os.Stat(filepath.Join(abs, "go.mod")); err != nil {
			return w, fmt.Errorf("--with %q: %s has no go.mod", s, abs)
		}
		w.Dir = abs
	case hasVer:
		if ver != "latest" && !versionRe.MatchString(ver) {
			return w, fmt.Errorf("--with %q: invalid version %q", s, ver)
		}
		w.Version = ver
	default:
		w.Version = "latest"
	}
	if path == DamsonModule && hasVer {
		return w, fmt.Errorf("--with %q: select the damson version with --damson-version", s)
	}
	return w, nil
}

func checkModulePath(p string) error {
	if p == "" || strings.HasPrefix(p, "-") || !modulePathRe.MatchString(p) {
		return errors.New("invalid module path")
	}
	for _, el := range strings.Split(p, "/") {
		if el == "" || el == "." || el == ".." {
			return errors.New("invalid module path")
		}
	}
	if !strings.Contains(strings.Split(p, "/")[0], ".") {
		return errors.New("the first element of a module path must contain a dot")
	}
	return nil
}

// damsonVersion returns the damson module version this binary was built from.
func damsonVersion(bi *debug.BuildInfo) (string, error) {
	if bi == nil {
		return "", errors.New("no build information in this binary")
	}
	m := &bi.Main
	if m.Path != DamsonModule {
		m = nil
		for _, d := range bi.Deps {
			if d.Path == DamsonModule {
				m = d
			}
		}
	}
	const hint = "this binary was built from a development checkout: pass --damson-version or --with " + DamsonModule + "=<dir>"
	if m == nil {
		return "", errors.New("the damson module is not in this binary's build information; pass --damson-version")
	}
	if m.Replace != nil || m.Version == "" || m.Version == "(devel)" || strings.HasSuffix(m.Version, "+dirty") {
		return "", errors.New(hint)
	}
	return m.Version, nil
}

// generateMain renders the main package of the custom binary.
func generateMain(withs []With) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by damson build. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	b.WriteString("\t\"" + DamsonModule + "/pkg/damsoncli\"\n")
	for i, w := range withs {
		fmt.Fprintf(&b, "\tp%d %s\n", i, strconv.Quote(w.Path))
	}
	b.WriteString(")\n\nfunc main() {\n\tdamsoncli.Main(damsoncli.Options{Modules: []damsoncli.Module{\n")
	for i, w := range withs {
		fmt.Fprintf(&b, "\t\t{Path: %s, Plugins: p%d.Plugins},\n", strconv.Quote(w.Path), i)
	}
	b.WriteString("\t}})\n}\n")
	return format.Source(b.Bytes())
}
